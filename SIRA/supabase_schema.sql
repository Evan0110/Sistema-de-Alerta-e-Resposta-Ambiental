CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    risk_type TEXT NOT NULL CHECK (risk_type IN ('Enchente','Deslizamento','Queimada','Seca','Qualidade do Ar','Contaminação de Água')),
    severity TEXT NOT NULL CHECK (severity IN ('Emergência','Alerta','Atenção')),
    location TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lng DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
    issuer TEXT NOT NULL,
    description TEXT NOT NULL,
    instructions TEXT NOT NULL,
    date_time TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS extension_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    organization TEXT NOT NULL,
    role TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS extension_feedbacks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_name TEXT NOT NULL,
    usability_rating INTEGER NOT NULL CHECK (usability_rating BETWEEN 1 AND 5),
    clarity_rating INTEGER NOT NULL CHECK (clarity_rating BETWEEN 1 AND 5),
    persona TEXT NOT NULL CHECK (persona IN ('Operador', 'Público geral')),
    comments TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE extension_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE extension_feedbacks ENABLE ROW LEVEL SECURITY;
